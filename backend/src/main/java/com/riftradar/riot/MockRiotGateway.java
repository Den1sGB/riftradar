package com.riftradar.riot;

import com.riftradar.riot.RiotDtos.RiotAccountDto;
import com.riftradar.riot.RiotDtos.RiotLeagueEntryDto;
import com.riftradar.riot.RiotDtos.RiotMatchDto;
import com.riftradar.riot.RiotDtos.RiotMatchDto.Info;
import com.riftradar.riot.RiotDtos.RiotMatchDto.Metadata;
import com.riftradar.riot.RiotDtos.RiotMatchDto.Participant;
import com.riftradar.riot.RiotDtos.RiotSummonerDto;
import java.nio.charset.StandardCharsets;
import java.time.Clock;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Random;
import java.util.UUID;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.stereotype.Component;

@Component
@ConditionalOnProperty(name = "riftradar.riot.mode", havingValue = "mock", matchIfMissing = true)
public class MockRiotGateway implements RiotGateway {

    private static final List<String> CHAMPIONS = List.of(
            "Ahri", "Jinx", "LeeSin", "Thresh", "Yasuo", "Lux", "Kaisa", "Vi", "Orianna", "Ezreal", "Sylas", "Gnar"
    );
    private static final List<String> LANES = List.of("TOP", "JUNGLE", "MIDDLE", "BOTTOM", "UTILITY");
    private static final List<String> TIERS = List.of("GOLD", "PLATINUM", "EMERALD", "DIAMOND", "MASTER");
    private static final List<String> RANKS = List.of("IV", "III", "II", "I");

    private final Clock clock;

    public MockRiotGateway(Clock clock) {
        this.clock = clock;
    }

    @Override
    public RiotAccountDto findAccountByRiotId(RiotRegion region, String gameName, String tagLine) {
        String key = (region.name() + ":" + gameName + "#" + tagLine).toLowerCase(Locale.ROOT);
        String puuid = "mock-" + UUID.nameUUIDFromBytes(key.getBytes(StandardCharsets.UTF_8));
        return new RiotAccountDto(puuid, gameName.trim(), tagLine.trim().toUpperCase(Locale.ROOT));
    }

    @Override
    public RiotSummonerDto findSummonerByPuuid(RiotRegion region, String puuid) {
        Random rng = new Random(puuid.hashCode());
        int iconId = 4500 + rng.nextInt(40);
        long level = 95L + rng.nextInt(380);
        return new RiotSummonerDto("sum-" + Math.abs(puuid.hashCode()), puuid, iconId, level);
    }

    @Override
    public List<RiotLeagueEntryDto> findLeagueEntries(RiotRegion region, String summonerId, String puuid) {
        Random rng = new Random(puuid.hashCode() * 31L);
        String tier = TIERS.get(rng.nextInt(TIERS.size()));
        String rank = "MASTER".equals(tier) ? "I" : RANKS.get(rng.nextInt(RANKS.size()));
        int lp = rng.nextInt(99);
        int wins = 45 + rng.nextInt(120);
        int losses = 40 + rng.nextInt(115);
        return List.of(new RiotLeagueEntryDto("RANKED_SOLO_5x5", tier, rank, lp, wins, losses));
    }

    @Override
    public List<String> findRecentMatchIds(RiotRegion region, String puuid, int count) {
        int safeCount = Math.min(Math.max(count, 1), 20);
        int seed = Math.abs(puuid.hashCode());
        List<String> ids = new ArrayList<>(safeCount);
        for (int i = 0; i < safeCount; i++) {
            ids.add(region.name() + "_" + (900000000L + (seed % 100000) * 100L + i) + "_" + Math.abs((puuid + i).hashCode() % 10000));
        }
        return ids;
    }

    @Override
    public RiotMatchDto findMatchById(RiotRegion region, String matchId) {
        long seed = matchId.hashCode();
        Random rng = new Random(seed);
        String targetPuuid = extractOrFallbackPuuid(matchId);
        // If findMatchById is called with a matchId generated by findRecentMatchIds, caller matches participant via index 0 fallback
        // unless we populate participant puuid cleanly. In SummonerService we resolve by exact matchId or first participant.
        String champion = CHAMPIONS.get(rng.nextInt(CHAMPIONS.size()));
        String lane = LANES.get(rng.nextInt(LANES.size()));
        boolean win = rng.nextInt(100) < 53;
        int kills = win ? 5 + rng.nextInt(10) : 1 + rng.nextInt(7);
        int deaths = win ? 1 + rng.nextInt(5) : 4 + rng.nextInt(7);
        int assists = 4 + rng.nextInt(12);
        int durationSec = 1380 + rng.nextInt(960);
        int csMinions = (durationSec / 60) * (5 + rng.nextInt(4));
        int vision = 14 + rng.nextInt(38);
        int gold = 9500 + rng.nextInt(7500);

        String[] parts = matchId.split("_");
        long idx = 0;
        try {
            idx = parts.length >= 2 ? Long.parseLong(parts[1]) % 100 : 0;
        } catch (NumberFormatException ignored) {
            idx = 0;
        }
        long gameCreation = Instant.now(clock).minusSeconds((idx + 1) * 5400L).toEpochMilli();

        Participant participant = new Participant(
                targetPuuid,
                champion,
                lane,
                win,
                kills,
                deaths,
                assists,
                csMinions,
                12 + rng.nextInt(35),
                vision,
                gold
        );
        return new RiotMatchDto(
                new Metadata(matchId),
                new Info(gameCreation, durationSec, 420, List.of(participant))
        );
    }

    private String extractOrFallbackPuuid(String matchId) {
        return "mock-participant:" + matchId;
    }

    @Override
    public String modeName() {
        return "mock";
    }
}
